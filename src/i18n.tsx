export const LANGUAGES = { es: 'Español', en: 'English' } as const
export type Lang = keyof typeof LANGUAGES
export const DICTS: Record<Lang, Record<Key, string>> = { es, en }

export type T = (key: Key, vars?: Record<string, string | number>) => string

const detect = (): Lang => (navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en')

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: T
  /** Number in the UI language with a fixed number of decimals. */
  num: (n: number, decimals?: number) => string
}
const I18nContext = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [stored, setLang] = usePersistentState<Lang>('lang', detect)
  const lang: Lang = stored in DICTS ? stored : 'en'
  const dict = DICTS[lang]
  const t: T = (key, vars) => (dict[key] ?? key).replace(/\{(\w+)\}/g, (_, v) => String(vars?.[v] ?? ''))
  const num = (n: number, decimals = 0) =>
    new Intl.NumberFormat(lang, { minimumFractionDigits: decimals, maximumFractionDigits: decimals }).format(n)
  document.documentElement.lang = lang
  return <I18nContext.Provider value={{ lang, setLang, t, num }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n outside I18nProvider')
  return ctx
}
